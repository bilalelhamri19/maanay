export function generateFor(id: string): string[] {
  const bank = BANKS[id];
  if (!bank) return [];
  const out: string[] = [];
  for (const a of bank.a) {
    for (const b of bank.b) {
      out.push(`${a}، ${b}.`);
      for (const c of bank.c) out.push(`${a}، ${b} ${c}`);
    }
  }
  // deterministic shuffle so consecutive quotes vary
  let s = id.length * 9973 + 17;
  const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
